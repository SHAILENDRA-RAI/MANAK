'use client';

import { useEffect, useState } from 'react';
import Link from 'next/link';
import {
  Brain,
  Calculator,
  RefreshCw,
  AlertCircle,
  CheckCircle2,
  Info,
  TrendingUp,
  TrendingDown,
  Minus,
} from 'lucide-react';

import { AppShell } from '@/components/app-shell';
import { Button } from '@/components/ui/button';
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from '@/components/ui/card';

import { supabase } from '@/lib/supabase';
import { useAuth } from '@/lib/auth-context';
import type { Valuation, Property, FeatureContribution } from '@/lib/types';

type ExplainableRecord = Valuation & {
  property: Property | null;
};

function currency(value: number | null | undefined) {
  if (value == null || !Number.isFinite(Number(value))) return '—';

  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(Number(value));
}

function percentage(value: number | null | undefined) {
  if (value == null || !Number.isFinite(Number(value))) return '—';
  return `${(Number(value) * 100).toFixed(1)}%`;
}

export default function ExplainableAIPage() {
  const { user } = useAuth();

  const [records, setRecords] = useState<ExplainableRecord[]>([]);
  const [selectedId, setSelectedId] = useState('');
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  async function loadValuations() {
    if (!user) {
      setLoading(false);
      return;
    }

    setLoading(true);
    setError('');

    const { data, error: queryError } = await supabase
      .from('valuations')
      .select('*, property:properties(*)')
      .eq('user_id', user.id)
      .order('created_at', { ascending: false });

    if (queryError) {
      setError(queryError.message);
      setRecords([]);
    } else {
      const result = (data || []) as ExplainableRecord[];
      setRecords(result);

      if (result.length > 0) {
        setSelectedId((current) =>
          result.some((item) => item.id === current)
            ? current
            : result[0].id
        );
      } else {
        setSelectedId('');
      }
    }

    setLoading(false);
  }

  useEffect(() => {
    loadValuations();
  }, [user]);

  const selected = records.find((item) => item.id === selectedId);

  const contributions: FeatureContribution[] =
    selected?.feature_contributions || [];

  const totalImpact = contributions.reduce(
    (sum, item) => sum + Math.abs(Number(item.impact || 0)),
    0
  );

  return (
    <AppShell
      breadcrumbs={[
        { label: 'Dashboard', href: '/dashboard' },
        { label: 'Explainable AI' },
      ]}
    >
      <div className="space-y-6">
        <div className="flex flex-col justify-between gap-4 sm:flex-row sm:items-center">
          <div className="flex items-center gap-3">
            <div className="rounded-lg bg-accent/10 p-3">
              <Brain className="h-6 w-6 text-accent" />
            </div>

            <div>
              <h1 className="text-2xl font-bold tracking-tight">
                Explainable AI
              </h1>
              <p className="text-sm text-muted-foreground">
                Inspect the factors recorded for each property estimate.
              </p>
            </div>
          </div>

          <Button variant="outline" onClick={loadValuations} disabled={loading}>
            <RefreshCw className={`mr-2 h-4 w-4 ${loading ? 'animate-spin' : ''}`} />
            Refresh
          </Button>
        </div>

        <div className="rounded-lg border border-amber-500/30 bg-amber-500/10 p-4">
          <div className="flex gap-3">
            <Info className="mt-0.5 h-5 w-5 shrink-0 text-amber-600" />
            <div>
              <p className="font-semibold text-sm">Model transparency notice</p>
              <p className="mt-1 text-sm text-muted-foreground">
                Current MANAK estimates use a documented comparable-based
                demonstration method. The feature contributions below are
                illustrative explanations generated by that method. They are
                not outputs from a trained machine learning model.
              </p>
            </div>
          </div>
        </div>

        {error && (
          <div className="flex items-start gap-2 rounded-lg border border-destructive/30 bg-destructive/10 p-4 text-sm text-destructive">
            <AlertCircle className="mt-0.5 h-4 w-4 shrink-0" />
            {error}
          </div>
        )}

        {loading ? (
          <div className="flex items-center justify-center gap-2 py-16 text-sm text-muted-foreground">
            <RefreshCw className="h-4 w-4 animate-spin" />
            Loading valuation explanations...
          </div>
        ) : records.length === 0 ? (
          <Card>
            <CardContent className="py-14 text-center">
              <Brain className="mx-auto h-10 w-10 text-muted-foreground" />
              <h2 className="mt-4 font-semibold">
                No valuation explanations available
              </h2>
              <p className="mt-2 text-sm text-muted-foreground">
                Generate a property estimate first to inspect its recorded factors.
              </p>
              <Button className="mt-5" asChild>
                <Link href="/valuation">
                  <Calculator className="mr-2 h-4 w-4" />
                  Generate Valuation
                </Link>
              </Button>
            </CardContent>
          </Card>
        ) : (
          <>
            <Card>
              <CardHeader>
                <CardTitle>Select a Valuation</CardTitle>
                <CardDescription>
                  Choose a previously generated estimate.
                </CardDescription>
              </CardHeader>

              <CardContent>
                <select
                  value={selectedId}
                  onChange={(event) => setSelectedId(event.target.value)}
                  className="h-11 w-full rounded-md border border-input bg-background px-3 text-sm"
                  aria-label="Select valuation"
                >
                  {records.map((record) => (
                    <option key={record.id} value={record.id}>
                      {record.property?.address || 'Property'} —{' '}
                      {currency(record.estimated_value)} —{' '}
                      {new Date(record.created_at).toLocaleDateString('en-IN')}
                    </option>
                  ))}
                </select>
              </CardContent>
            </Card>

            {selected && (
              <>
                <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
                  <Card>
                    <CardContent className="p-5">
                      <p className="text-sm text-muted-foreground">
                        Estimated Value
                      </p>
                      <p className="mt-2 text-xl font-bold">
                        {currency(selected.estimated_value)}
                      </p>
                    </CardContent>
                  </Card>

                  <Card>
                    <CardContent className="p-5">
                      <p className="text-sm text-muted-foreground">
                        Price per sq.ft.
                      </p>
                      <p className="mt-2 text-xl font-bold">
                        {currency(selected.price_per_sqft)}
                      </p>
                    </CardContent>
                  </Card>

                  <Card>
                    <CardContent className="p-5">
                      <p className="text-sm text-muted-foreground">
                        Recorded Confidence
                      </p>
                      <p className="mt-2 text-xl font-bold">
                        {percentage(selected.confidence)}
                      </p>
                    </CardContent>
                  </Card>

                  <Card>
                    <CardContent className="p-5">
                      <p className="text-sm text-muted-foreground">
                        Comparable Records
                      </p>
                      <p className="mt-2 text-xl font-bold">
                        {selected.comparables_count}
                      </p>
                    </CardContent>
                  </Card>
                </div>

                <Card>
                  <CardHeader>
                    <CardTitle>Valuation Range</CardTitle>
                    <CardDescription>
                      Recorded lower and upper estimate bounds.
                    </CardDescription>
                  </CardHeader>

                  <CardContent>
                    <div className="grid gap-4 sm:grid-cols-3">
                      <div className="rounded-lg bg-muted/40 p-4">
                        <p className="text-xs text-muted-foreground">
                          Lower Bound
                        </p>
                        <p className="mt-2 font-semibold">
                          {currency(selected.lower_bound)}
                        </p>
                      </div>

                      <div className="rounded-lg border border-accent/40 bg-accent/5 p-4">
                        <p className="text-xs text-muted-foreground">
                          Estimated Value
                        </p>
                        <p className="mt-2 text-lg font-bold">
                          {currency(selected.estimated_value)}
                        </p>
                      </div>

                      <div className="rounded-lg bg-muted/40 p-4">
                        <p className="text-xs text-muted-foreground">
                          Upper Bound
                        </p>
                        <p className="mt-2 font-semibold">
                          {currency(selected.upper_bound)}
                        </p>
                      </div>
                    </div>
                  </CardContent>
                </Card>

                <Card>
                  <CardHeader>
                    <CardTitle>Property Information</CardTitle>
                    <CardDescription>
                      Property details associated with this estimate.
                    </CardDescription>
                  </CardHeader>

                  <CardContent>
                    <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
                      <div>
                        <p className="text-xs text-muted-foreground">Address</p>
                        <p className="mt-1 text-sm font-medium">
                          {selected.property?.address || '—'}
                        </p>
                      </div>

                      <div>
                        <p className="text-xs text-muted-foreground">Locality</p>
                        <p className="mt-1 text-sm font-medium">
                          {selected.property?.locality || '—'}
                        </p>
                      </div>

                      <div>
                        <p className="text-xs text-muted-foreground">Property Type</p>
                        <p className="mt-1 text-sm font-medium capitalize">
                          {selected.property?.property_type?.replaceAll('_', ' ') || '—'}
                        </p>
                      </div>

                      <div>
                        <p className="text-xs text-muted-foreground">Area</p>
                        <p className="mt-1 text-sm font-medium">
                          {selected.property?.carpet_area ||
                            selected.property?.built_up_area ||
                            '—'}{' '}
                          sq.ft.
                        </p>
                      </div>

                      <div>
                        <p className="text-xs text-muted-foreground">Condition</p>
                        <p className="mt-1 text-sm font-medium capitalize">
                          {selected.property?.property_condition || '—'}
                        </p>
                      </div>

                      <div>
                        <p className="text-xs text-muted-foreground">Furnishing</p>
                        <p className="mt-1 text-sm font-medium capitalize">
                          {selected.property?.furnishing?.replaceAll('_', ' ') || '—'}
                        </p>
                      </div>
                    </div>
                  </CardContent>
                </Card>

                <Card>
                  <CardHeader>
                    <CardTitle>Recorded Feature Contributions</CardTitle>
                    <CardDescription>
                      Factors and adjustment descriptions stored with this valuation.
                    </CardDescription>
                  </CardHeader>

                  <CardContent>
                    {contributions.length === 0 ? (
                      <div className="py-8 text-center text-sm text-muted-foreground">
                        No feature contribution details were saved for this valuation.
                      </div>
                    ) : (
                      <div className="space-y-5">
                        {contributions.map((item, index) => {
                          const share =
                            totalImpact > 0
                              ? (Math.abs(Number(item.impact || 0)) / totalImpact) * 100
                              : 0;

                          const positive = item.direction === 'positive';

                          return (
                            <div key={`${item.feature}-${index}`} className="space-y-2">
                              <div className="flex flex-col justify-between gap-2 sm:flex-row sm:items-center">
                                <div className="flex items-center gap-2">
                                  {positive ? (
                                    <TrendingUp className="h-4 w-4 text-emerald-600" />
                                  ) : item.direction === 'negative' ? (
                                    <TrendingDown className="h-4 w-4 text-destructive" />
                                  ) : (
                                    <Minus className="h-4 w-4 text-muted-foreground" />
                                  )}

                                  <span className="font-medium text-sm">
                                    {item.label}
                                  </span>
                                </div>

                                <span className="text-xs text-muted-foreground">
                                  Recorded impact: {percentage(item.impact)}
                                </span>
                              </div>

                              <div className="h-2 overflow-hidden rounded-full bg-muted">
                                <div
                                  className="h-full rounded-full bg-accent"
                                  style={{ width: `${Math.min(100, share)}%` }}
                                />
                              </div>

                              <p className="text-sm text-muted-foreground">
                                {item.description}
                              </p>
                            </div>
                          );
                        })}
                      </div>
                    )}
                  </CardContent>
                </Card>

                <Card>
                  <CardHeader>
                    <CardTitle>Method and Data Notes</CardTitle>
                    <CardDescription>
                      Stored metadata for this estimate.
                    </CardDescription>
                  </CardHeader>

                  <CardContent className="space-y-3 text-sm">
                    <div className="flex justify-between gap-3">
                      <span className="text-muted-foreground">Valuation type</span>
                      <span className="font-medium uppercase">
                        {selected.valuation_type}
                      </span>
                    </div>

                    <div className="flex justify-between gap-3">
                      <span className="text-muted-foreground">Model version</span>
                      <span className="font-medium">
                        {selected.model_version || '—'}
                      </span>
                    </div>

                    <div className="flex justify-between gap-3">
                      <span className="text-muted-foreground">Data quality</span>
                      <span className="font-medium capitalize">
                        {selected.data_quality || '—'}
                      </span>
                    </div>

                    <div className="flex justify-between gap-3">
                      <span className="text-muted-foreground">Status</span>
                      <span className="font-medium capitalize">
                        {selected.status.replaceAll('_', ' ')}
                      </span>
                    </div>

                    {selected.notes && (
                      <div className="rounded-lg bg-muted/40 p-4 text-muted-foreground">
                        {selected.notes}
                      </div>
                    )}
                  </CardContent>
                </Card>
              </>
            )}
          </>
        )}

        <div className="flex items-start gap-2 rounded-lg border p-4 text-xs text-muted-foreground">
          <CheckCircle2 className="mt-0.5 h-4 w-4 shrink-0" />
          MANAK provides an automated estimate for preliminary property and
          collateral assessment. It is not a formal valuation certificate,
          does not replace physical inspection or professional valuation,
          and must not be treated as a loan approval or lending decision.
        </div>
      </div>
    </AppShell>
  );
}
